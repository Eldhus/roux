//! The app's module for each template (`Menu.roc`): its contract (`Ctx`)
//! and `template`, one line, which makes the template's value: its tag of
//! the app's `Templates.Template`, which `Templates.roc` (also written here)
//! spells out. Written from the contracts alone, so a markup edit leaves
//! the modules as they are, unless it changes what a fragment reads. A
//! page's fragments are nested in its module (`Menu.Row`).
//!
//! The holes' Roc is in `Holes.roc`, apart: an edit of a hole changes a
//! template's module only when it changes what the template takes.
//!
//! Roc source uses tabs, which Zig's multiline strings cannot hold: they
//! are written as `\t`.

const std = @import("std");
const assert = std.debug.assert;
const Writer = std.Io.Writer;
const Allocator = std.mem.Allocator;
const contract_ = @import("contract.zig");
const Contract = contract_.Contract;

/// A record or list type longer than this (with its indentation) is
/// written one field per line.
const line_columns_max = 72;

pub const Module = struct {
    /// `Menu` for `Menu.rocstache`.
    name: []const u8,
    contract: *const Contract,
    /// Its fragments, in source order, nested in it: `Menu.Row`.
    fragments: []const Fragment = &.{},
};

/// A hole's Roc function: `hole_<key>` in `Holes.roc`, the tag `H<key>` of
/// the app's `Holes.Hole`.
pub const Hole = struct {
    key: u64,
    /// The template whose text holds it.
    template: []const u8,
    expression: []const u8,
    /// Its parameters' record, as one line of Roc.
    params: []const u8,
    /// The record's fields, sorted: the names the expression reads.
    names: []const []const u8,
};

/// `{{$Row}}` in `Menu.rocstache`: `Menu.Row`, its tag `MenuRow`.
pub const Fragment = struct {
    name: []const u8,
    tag: []const u8,
    contract: *const Contract,
};

pub const Error = Writer.Error || Allocator.Error;

/// The app's `Menu.roc`.
pub fn write_module(module: Module, writer: *Writer) Error!void {
    const header = "# Generated by roux build from {s}.rocstache. DO NOT EDIT.\n";
    try writer.print(header, .{module.name});
    if (!module.contract.alone) return write_partial(module, writer);
    try writer.writeAll(if (module.fragments.len == 0)
        "# Its contract only: markup changes leave this file alone.\n"
    else
        "# Its contracts only: markup changes leave this file alone,\n" ++
            "# unless they change what a fragment reads.\n");
    try writer.writeAll("import pf.Rocstache\nimport Templates\n");
    // The partials it calls, whose contracts its own names (`Top.Ctx`).
    const contract = module.contract;
    for (contract.types[0..contract.types_len], 0..) |type_, index| {
        if (type_.alias.len == 0) continue;
        const first = for (contract.types[0..index]) |earlier| {
            if (std.mem.eql(u8, earlier.alias, type_.alias)) break false;
        } else true;
        if (first) try writer.print("import {s}\n", .{type_.alias});
    }
    try writer.print("\n{s} :: [].{{\n\n", .{module.name});
    // A fragment's contract is spelled out, never naming a sibling's, so
    // the order is the source's.
    for (module.fragments) |f| {
        try writer.print(
            "\t## The `{{{{${0s}}}}}` fragment of `{1s}.rocstache`: what it reads of\n" ++
                "\t## its scope there, rendered alone.\n" ++
                "\t{0s} :: [].{{\n\t\tCtx : ",
            .{ f.name, module.name },
        );
        try write_type(f.contract, f.contract.root, 2, writer);
        try write_fragment_template(f, writer);
    }
    if (module.contract.docs.len > 0) {
        var lines = std.mem.splitScalar(u8, module.contract.docs, '\n');
        while (lines.next()) |line| try writer.print("\t{s}\n", .{std.mem.trim(u8, line, " \t")});
    } else {
        const inferred = "\t## What `{s}.rocstache` reads, inferred from its tags.\n";
        try writer.print(inferred, .{module.name});
    }
    try writer.writeAll("\tCtx : ");
    try write_type(module.contract, module.contract.root, 1, writer);
    try writer.print(
        "\n\n\t## The template's value: what a response sends, rendered by the\n" ++
            "\t## host from the template's bytecode as it is sent.\n" ++
            "\ttemplate : Ctx -> Rocstache.Template(Templates.Template)\n" ++
            "\ttemplate = |ctx| {{ layouts: Templates.layouts, template: {s}(ctx) }}\n",
        .{module.name},
    );
    try writer.writeAll("}\n");
}

/// A partial that renders only where it is included: no contract of its
/// own, no `template`; its holes' Roc is in `Holes.roc`.
fn write_partial(module: Module, writer: *Writer) Error!void {
    assert(!module.contract.alone);
    assert(module.fragments.len == 0);
    try writer.writeAll("# A partial whose holes' Roc reads the scope where it is included:\n" ++
        "# it renders only there, and takes nothing of its own.\n");
    try writer.print("\n{s} :: [].{{}}\n", .{module.name});
}

/// Each hole's Roc, as written in the template, a function of the names it
/// reads: Roc checks it there, and its errors quote it.
fn write_hole_functions(holes: []const Hole, writer: *Writer) Writer.Error!void {
    for (holes) |h| {
        try writer.print("\n\t## `{{{{ {s} }}}}` in {s}.rocstache\n", .{
            first_line(h.expression), h.template,
        });
        try writer.print("\thole_{x:0>16} : {s} -> Str\n", .{ h.key, h.params });
        try writer.print("\thole_{x:0>16} = |{{", .{h.key});
        for (h.names, 0..) |name, k| {
            try writer.print("{s} {s}", .{ if (k == 0) "" else ",", name });
        }
        try writer.print("{s}}}| ({s})\n", .{ if (h.names.len == 0) "" else " ", h.expression });
    }
}

fn first_line(text: []const u8) []const u8 {
    return text[0 .. std.mem.indexOfScalar(u8, text, '\n') orelse text.len];
}

/// The app's `Holes.roc`: every hole of its templates, a tag each holding
/// what it reads, each hole's Roc, and `hole`, which the host calls with
/// one. It imports what the templates' blocks import, for their holes.
/// Generated on every build and not kept in version control: a hole's edit
/// changes it alone.
pub fn write_holes(holes: []const Hole, imports: []const []const u8, writer: *Writer) Error!void {
    try writer.writeAll("# Generated by roux build from the app's templates. DO NOT EDIT.\n" ++
        "# The holes whose Roc it compiles; the renderer calls `hole` at each.\n");
    for (imports) |name| try writer.print("import {s}\n", .{name});
    try writer.writeAll("\nHoles :: [].{\n" ++
        "\t## Every hole of the app's templates that Roc computes, a tag each,\n" ++
        "\t## holding the values it reads.\n" ++
        "\tHole : [\n");
    // A union of no tags has no values: an app with no such hole has one,
    // which no template makes.
    if (holes.len == 0) try writer.writeAll("\t\tNone,\n");
    for (holes) |h| try writer.print("\t\tH{x:0>16}({s}),\n", .{ h.key, h.params });
    try writer.writeAll("\t]\n\n" ++
        "\t## A hole's Str: the host calls it where the hole stands.\n" ++
        "\thole : Hole -> Str\n" ++
        "\thole = |h|\n\t\tmatch h {\n");
    if (holes.len == 0) try writer.writeAll("\t\t\tNone => \"\"\n");
    for (holes) |h| {
        try writer.print("\t\t\tH{x:0>16}(reads) => Holes.hole_{x:0>16}(reads)\n", .{
            h.key, h.key,
        });
    }
    try writer.writeAll("\t\t}\n");
    try write_hole_functions(holes, writer);
    try writer.writeAll("}\n");
}

/// Generated Roc stays within this many columns where it can (a tab is 4).
const columns_max = 100;

/// A fragment's `template` takes any record with the fields it reads, as
/// Roc's `|{ name, .. }|` does, and keeps those: a handler passes the
/// element or the page it has. Laid out as `roc fmt` keeps it.
fn write_fragment_template(f: Fragment, writer: *Writer) Writer.Error!void {
    const contract = f.contract;
    const result = " -> Rocstache.Template(Templates.Template)";
    var line_buffer: [columns_max]u8 = undefined;
    var line: Writer = .fixed(&line_buffer);
    const fits = if (write_open_record(contract, &line)) |_|
        8 + "template : ".len + line.buffered().len + result.len <= columns_max
    else |_|
        false;
    try writer.writeAll("\n\n\t\ttemplate : ");
    if (fits) {
        try writer.writeAll(line.buffered());
    } else {
        try writer.writeAll("{\n");
        var fields = contract.fields_of(contract.root);
        while (fields.next()) |field| {
            try writer.print("\t\t\t{s} : ", .{field.name});
            try write_type(contract, field.type, 3, writer);
            try writer.writeAll(",\n");
        }
        try writer.writeAll("\t\t\t..,\n\t\t}");
    }
    try writer.print("{s}\n\t\ttemplate = |", .{result});
    line = .fixed(&line_buffer);
    const body_fits = if (write_body(f, &line)) |_|
        8 + "template = |".len + names_width(contract) + "| ".len + line.buffered().len <=
            columns_max
    else |_|
        false;
    var fields = contract.fields_of(contract.root);
    if (fields.next() == null) {
        try writer.writeAll("_|");
    } else {
        try write_names(contract, "{ ", ", .. }", writer);
        try writer.writeAll("|");
    }
    try writer.writeAll(if (body_fits) " " else "\n\t\t\t");
    try write_body(f, writer);
    try writer.writeAll("\n\t}\n\n");
}

/// `{ id : U64, name : Str, .. }`, on one line.
fn write_open_record(contract: *const Contract, writer: *Writer) Writer.Error!void {
    var fields = contract.fields_of(contract.root);
    try writer.writeAll("{ ");
    while (fields.next()) |field| {
        try writer.print("{s} : ", .{field.name});
        try contract_.write_line_as(contract, field.type, writer, .named);
        try writer.writeAll(", ");
    }
    try writer.writeAll(".. }");
}

/// `{ layouts: Templates.layouts, template: MenuRow({ id, name }) }`.
fn write_body(f: Fragment, writer: *Writer) Writer.Error!void {
    const contract = f.contract;
    try writer.print("{{ layouts: Templates.layouts, template: {s}(", .{f.tag});
    var fields = contract.fields_of(contract.root);
    const first = fields.next();
    if (first == null) {
        try writer.writeAll("{}");
    } else if (fields.next() == null) {
        // `{ count }` alone is a block that returns `count`.
        try writer.print("{{ {s}: {s} }}", .{ first.?.name, first.?.name });
    } else {
        try write_names(contract, "{ ", " }", writer);
    }
    try writer.writeAll(") }");
}

fn names_width(contract: *const Contract) usize {
    var width: usize = "{ , .. }".len;
    var fields = contract.fields_of(contract.root);
    while (fields.next()) |field| width += field.name.len + ", ".len;
    return width;
}

fn write_names(
    contract: *const Contract,
    open: []const u8,
    close: []const u8,
    writer: *Writer,
) Writer.Error!void {
    try writer.writeAll(open);
    var fields = contract.fields_of(contract.root);
    var k: usize = 0;
    while (fields.next()) |field| : (k += 1) {
        try writer.print("{s}{s}", .{ if (k == 0) "" else ", ", field.name });
    }
    try writer.writeAll(close);
}

pub const Union = struct {
    /// What renders alone, each page followed by its fragments (`Menu`,
    /// `MenuRow`), and their contracts.
    names: []const []const u8,
    contracts: []const *const Contract,
    /// The layouts' identity (generate.zig), which the program carries.
    layouts: u64,
};

/// The app's `Templates.roc`: the union of its templates, a tag each, its
/// payload the template's contract spelled out (a template's module
/// imports this one, so it cannot import them), and the layouts' identity.
/// Every constructor's annotation names the whole union, so Roc lays out
/// the one glue laid out, whichever templates the app sends.
pub fn write_templates(templates: Union, writer: *Writer) Error!void {
    assert(templates.names.len == templates.contracts.len);
    try writer.writeAll("# Generated by roux build from the app's templates. DO NOT EDIT.\n" ++
        "# The contracts spelled out, so each template's module can import this one.\n" ++
        "\nTemplates :: [].{\n" ++
        "\t## Every template of the app, a tag each, holding what it reads.\n" ++
        "\tTemplate : [\n");
    for (templates.names, templates.contracts) |name, contract| {
        try writer.print("\t\t{s}(", .{name});
        try contract_.write_line(contract, contract.root, writer);
        try writer.writeAll("),\n");
    }
    try writer.print("\t]\n\n" ++
        "\t## The layouts these templates were compiled for: the host renders\n" ++
        "\t## only a value made for its program's.\n" ++
        "\tlayouts : U64\n" ++
        "\tlayouts = 0x{x:0>16}\n}}\n", .{templates.layouts});
}

/// A type as `roc fmt` lays it out: on one line when it fits, else a
/// record one field per line, with a trailing comma.
fn write_type(
    contract: *const Contract,
    index: u16,
    indent: u8,
    writer: *Writer,
) Writer.Error!void {
    assert(indent < 64);
    var line_buffer: [line_columns_max]u8 = undefined;
    var line: Writer = .fixed(&line_buffer);
    const fits = if (contract_.write_line_as(contract, index, &line, .named)) |_|
        @as(usize, indent) * 4 + line.buffered().len <= line_columns_max
    else |_|
        false;
    if (fits) return writer.writeAll(line.buffered());
    const type_ = contract.get(index);
    if (index != contract.root and type_.alias.len > 0) {
        return writer.print("{s}.Ctx", .{type_.alias});
    }
    switch (type_.kind) {
        .list => {
            try writer.writeAll("List(\n");
            try write_tabs(indent + 1, writer);
            try write_type(contract, type_.element, indent + 1, writer);
            try writer.writeAll(",\n");
            try write_tabs(indent, writer);
            try writer.writeAll(")");
        },
        .record => {
            try writer.writeAll("{\n");
            var fields = contract.fields_of(index);
            while (fields.next()) |f| {
                try write_tabs(indent + 1, writer);
                try writer.print("{s} : ", .{f.name});
                try write_type(contract, f.type, indent + 1, writer);
                try writer.writeAll(",\n");
            }
            try write_tabs(indent, writer);
            try writer.writeAll("}");
        },
        .unknown, .str, .int, .bool, .other => unreachable,
    }
}

fn write_tabs(count: u8, writer: *Writer) Writer.Error!void {
    for (0..count) |_| try writer.writeAll("\t");
}

const testing = std.testing;

test "roc: a page's module nests its fragments, each taking any record with its fields" {
    const parse = @import("parse.zig");
    const source = "{{% Ctx : { a : Str, b : U64, items : List({ id : U64, name : Str }) } %}}" ++
        "{{$Hello}}x{{/Hello}}{{$One}}{{ a }}{{/One}}" ++
        "{{$Two}}{{ a }}{{ b | plural \"x\" \"y\" }}{{/Two}}" ++
        "{{#items |item|}}{{$Row}}{{ item.id }}{{ item.name }}{{/Row}}{{/items}}";
    var tree: parse.Tree = .{};
    var d: parse.Diagnostic = .{};
    try parse.parse(source, &tree, &d);
    const page = try testing.allocator.create(Contract);
    defer testing.allocator.destroy(page);
    var diagnostic: contract_.Diagnostic = .{};
    try contract_.of(page, &.{.{ .name = "Page", .source = source, .tree = &tree }}, &diagnostic);
    var contracts: [4]Contract = undefined;
    var fragments: [4]Fragment = undefined;
    for (page.fragment_slice(), 0..) |f, k| {
        try contract_.of_fragment(&contracts[k], page, @intCast(k));
        const tags = [_][]const u8{ "PageHello", "PageOne", "PageTwo", "PageRow" };
        fragments[k] = .{ .name = f.name, .tag = tags[k], .contract = &contracts[k] };
    }
    var buffer: [4096]u8 = undefined;
    var writer: Writer = .fixed(&buffer);
    try write_module(.{ .name = "Page", .contract = page, .fragments = &fragments }, &writer);
    const result = " -> Rocstache.Template(Templates.Template)\n";
    // On one line when it fits in 100 columns (Two), else the body below (Row).
    try testing.expectEqualStrings(
        "# Generated by roux build from Page.rocstache. DO NOT EDIT.\n" ++
            "# Its contracts only: markup changes leave this file alone,\n" ++
            "# unless they change what a fragment reads.\n" ++
            "import pf.Rocstache\nimport Templates\n\nPage :: [].{\n\n" ++
            "\t## The `{{$Hello}}` fragment of `Page.rocstache`: what it reads of\n" ++
            "\t## its scope there, rendered alone.\n" ++
            "\tHello :: [].{\n\t\tCtx : {}\n\n" ++
            "\t\ttemplate : { .. }" ++ result ++
            "\t\ttemplate = |_| { layouts: Templates.layouts, template: PageHello({}) }\n\t}\n\n" ++
            "\t## The `{{$One}}` fragment of `Page.rocstache`: what it reads of\n" ++
            "\t## its scope there, rendered alone.\n" ++
            "\tOne :: [].{\n\t\tCtx : { a : Str }\n\n" ++
            "\t\ttemplate : { a : Str, .. }" ++ result ++
            "\t\ttemplate = |{ a, .. }| " ++
            "{ layouts: Templates.layouts, template: PageOne({ a: a }) }\n\t}\n\n" ++
            "\t## The `{{$Two}}` fragment of `Page.rocstache`: what it reads of\n" ++
            "\t## its scope there, rendered alone.\n" ++
            "\tTwo :: [].{\n\t\tCtx : { a : Str, b : U64 }\n\n" ++
            "\t\ttemplate : { a : Str, b : U64, .. }" ++ result ++
            "\t\ttemplate = |{ a, b, .. }| " ++
            "{ layouts: Templates.layouts, template: PageTwo({ a, b }) }\n\t}\n\n" ++
            "\t## The `{{$Row}}` fragment of `Page.rocstache`: what it reads of\n" ++
            "\t## its scope there, rendered alone.\n" ++
            "\tRow :: [].{\n\t\tCtx : { id : U64, name : Str }\n\n" ++
            "\t\ttemplate : { id : U64, name : Str, .. }" ++ result ++
            "\t\ttemplate = |{ id, name, .. }|\n" ++
            "\t\t\t{ layouts: Templates.layouts, template: PageRow({ id, name }) }\n\t}\n\n" ++
            "\t## What `Page.rocstache` reads, inferred from its tags.\n" ++
            "\tCtx : { a : Str, b : U64, items : List({ id : U64, name : Str }) }\n\n" ++
            "\t## The template's value: what a response sends, rendered by the\n" ++
            "\t## host from the template's bytecode as it is sent.\n" ++
            "\ttemplate : Ctx -> Rocstache.Template(Templates.Template)\n" ++
            "\ttemplate = |ctx| { layouts: Templates.layouts, template: Page(ctx) }\n}\n",
        writer.buffered(),
    );
}

test "roc: the holes' Roc is all in Holes.roc, under the blocks' imports" {
    const holes = [_]Hole{.{
        .key = 0xab,
        .template = "Price",
        .expression = "Fmt.kr(item.price)",
        .params = "{ item : { price : U32 } }",
        .names = &.{"item"},
    }};
    var buffer: [2048]u8 = undefined;
    var writer: Writer = .fixed(&buffer);
    try write_holes(&holes, &.{"Fmt"}, &writer);
    try testing.expectEqualStrings(
        "# Generated by roux build from the app's templates. DO NOT EDIT.\n" ++
            "# The holes whose Roc it compiles; the renderer calls `hole` at each.\n" ++
            "import Fmt\n\nHoles :: [].{\n" ++
            "\t## Every hole of the app's templates that Roc computes, a tag each,\n" ++
            "\t## holding the values it reads.\n" ++
            "\tHole : [\n\t\tH00000000000000ab({ item : { price : U32 } }),\n\t]\n\n" ++
            "\t## A hole's Str: the host calls it where the hole stands.\n" ++
            "\thole : Hole -> Str\n\thole = |h|\n\t\tmatch h {\n" ++
            "\t\t\tH00000000000000ab(reads) => Holes.hole_00000000000000ab(reads)\n\t\t}\n\n" ++
            "\t## `{{ Fmt.kr(item.price) }}` in Price.rocstache\n" ++
            "\thole_00000000000000ab : { item : { price : U32 } } -> Str\n" ++
            "\thole_00000000000000ab = |{ item }| (Fmt.kr(item.price))\n}\n",
        writer.buffered(),
    );
}
