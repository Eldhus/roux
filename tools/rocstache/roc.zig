//! The app's module for each template (`Page.roc`): its contract, a pure
//! `render`, and the walkers that run the template's bytecode over the
//! contract (bytecode.zig): one per scope of the contract, each a loop
//! over the words with a branch per op, and in each branch a `match` on
//! the selector over the fields that op can read there. They are written
//! from the contract alone, so a markup edit leaves the module as it is.
//!
//! Roc source uses tabs, which Zig's multiline strings cannot hold: they
//! are written as `\t`.

const std = @import("std");
const assert = std.debug.assert;
const Writer = std.Io.Writer;
const Allocator = std.mem.Allocator;
const contract_ = @import("contract.zig");
const Contract = contract_.Contract;
const bytecode = @import("bytecode.zig");
const Op = bytecode.Op;

/// A record or list type longer than this (with its indentation) is
/// written one field per line.
const line_columns_max = 72;

pub const Module = struct {
    /// `Page` for `Page.rocstache`.
    name: []const u8,
    contract: *const Contract,
    /// The template's index among the app's, sorted by name: where the
    /// code's header has its range.
    index: u32,
};

pub const Error = Writer.Error || Allocator.Error;

/// The app's `Page.roc`.
pub fn write_module(gpa: Allocator, module: Module, writer: *Writer) Error!void {
    try writer.print(
        "# Generated by roux build from {0s}.rocstache. DO NOT EDIT.\n" ++
            "# Its contract and walkers only: markup changes leave this file alone.\n" ++
            "import pf.Rocstache\n",
        .{module.name},
    );
    // The partials it calls, whose contracts its own names (`Top.Ctx`).
    const contract = module.contract;
    for (contract.types[0..contract.types_len], 0..) |type_, index| {
        if (type_.alias.len == 0) continue;
        const first = for (contract.types[0..index]) |earlier| {
            if (std.mem.eql(u8, earlier.alias, type_.alias)) break false;
        } else true;
        if (first) try writer.print("import {s}\n", .{type_.alias});
    }
    try writer.print("\n{s} :: [].{{\n\n", .{module.name});
    if (module.contract.docs.len > 0) {
        var lines = std.mem.splitScalar(u8, module.contract.docs, '\n');
        while (lines.next()) |line| try writer.print("\t{s}\n", .{std.mem.trim(u8, line, " \t")});
    } else {
        const inferred = "\t## What `{s}.rocstache` reads, inferred from its tags.\n";
        try writer.print(inferred, .{module.name});
    }
    try writer.writeAll("\tCtx : ");
    try write_type(module.contract, module.contract.root, 1, writer);
    try writer.print(
        "\n\n\t## The page as parts, from the templates' bytecode (`Rocstache.load!`):\n" ++
            "\t## `Rocstache.bytes!` writes them out.\n" ++
            "\trender : Rocstache.Templates, Ctx -> Rocstache.Html\n" ++
            "\trender = |code, ctx| walk(code, ctx, List.with_capacity(64))\n\n" ++
            "\t## The page's parts after `parts`: how a template calling this one\n" ++
            "\t## renders it.\n" ++
            "\twalk : Rocstache.Templates, Ctx, Rocstache.Html -> Rocstache.Html\n" ++
            "\twalk = |code, ctx, parts| {{\n" ++
            "\t\tstart = List.get(code, {d}) ?? 0\n" ++
            "\t\tend = List.get(code, {d}) ?? 0\n" ++
            "\t\tw{d}(ctx, code, start, end, parts)\n" ++
            "\t}}\n}}\n",
        .{ 1 + 2 * module.index, 2 + 2 * module.index, contract.root },
    );
    var parents: [contract_.types_max]u16 = undefined;
    bytecode.scope_parents(contract, &parents);
    for (0..contract.types_len) |index| {
        const type_: u16 = @intCast(index);
        if (!bytecode.is_scope(contract, &parents, type_)) continue;
        try write_walker(gpa, module, &parents, type_, writer);
    }
}

/// A scope's walker: `w<type>(s0, s1, ..., code, start, end, parts)`, s0
/// the scope, s1 the one the contract holds it in, up to the root.
fn write_walker(
    gpa: Allocator,
    module: Module,
    parents: []const u16,
    scope: u16,
    writer: *Writer,
) Error!void {
    var walker: Walker = .{ .gpa = gpa, .module = module, .parents = parents };
    var at = scope;
    while (true) {
        walker.chain[walker.chain_len] = at;
        walker.chain_len += 1;
        if (parents[at] == bytecode.none) break;
        at = parents[at];
    }
    assert(at == module.contract.root);
    var body: Writer.Allocating = .init(gpa);
    try walker.body(&body.writer);

    try writer.print("\nw{d} : ", .{scope});
    for (walker.chain[0..walker.chain_len]) |t| {
        try walker.write_scope_type(t, writer);
        try writer.writeAll(", ");
    }
    try writer.print(
        "Rocstache.Templates, U64, U64, Rocstache.Html -> Rocstache.Html\nw{d} = |",
        .{scope},
    );
    for (0..walker.chain_len) |k| {
        try writer.print("{s}s{d}, ", .{ if (walker.used[k]) "" else "_", k });
    }
    try writer.writeAll("code, start, end, parts| {\n" ++
        "\tvar $parts = parts\n\tvar $pc = start\n\twhile $pc < end {\n" ++
        "\t\tw = List.get(code, $pc) ?? 0\n\t\top = w % 16\n" ++
        "\t\tif op == 0 {\n" ++
        "\t\t\t$parts = $parts.append(Text(w // 1048576))\n\t\t\t$pc = $pc + 1\n");
    try writer.writeAll(body.written());
    try writer.writeAll("\t\t} else {\n\t\t\t$pc = $pc + 1\n\t\t}\n\t}\n\t$parts\n}\n");
}

const Walker = struct {
    gpa: Allocator,
    module: Module,
    parents: []const u16,
    /// The scope, then those holding it, up to the root.
    chain: [16]u16 = undefined,
    chain_len: u8 = 0,
    /// Which of s0, s1, ... a branch reads.
    used: [16]bool = @splat(false),

    /// What a selector can name: s<k> itself, or a field of it.
    const Read = struct {
        selector: u16,
        k: u8,
        name: ?[]const u8,
        type_: u16,
    };

    /// Every read the walker's scopes allow: each scope itself, and its
    /// fields.
    fn reads(walker: *Walker, out: *std.ArrayList(Read)) Allocator.Error!void {
        const contract = walker.module.contract;
        for (walker.chain[0..walker.chain_len], 0..) |t, k| {
            const up: u8 = @intCast(k);
            try out.append(walker.gpa, .{
                .selector = bytecode.selector(up, bytecode.field_self),
                .k = up,
                .name = null,
                .type_ = t,
            });
            if (contract.get(t).kind != .record) continue;
            var buffer: [contract_.fields_max]contract_.Field = undefined;
            for (contract.sorted_fields(t, &buffer), 0..) |f, i| {
                try out.append(walker.gpa, .{
                    .selector = bytecode.selector(up, @intCast(i)),
                    .k = up,
                    .name = f.name,
                    .type_ = f.type,
                });
            }
        }
    }

    fn body(walker: *Walker, writer: *Writer) Error!void {
        var all: std.ArrayList(Read) = .empty;
        try walker.reads(&all);
        const ops = [_]Op{ .str, .num, .section, .inverted, .cond, .len, .plural, .call };
        for (ops) |op| {
            var cases: Writer.Allocating = .init(walker.gpa);
            for (all.items) |read| try walker.case(op, read, &cases.writer);
            if (cases.written().len == 0) continue;
            try writer.print("\t\t}} else if op == {d} {{\n", .{@backingInt(op)});
            try writer.writeAll(switch (op) {
                .str, .num, .len => "\t\t\trun = List.get(code, $pc + 1) ?? 0\n",
                .plural => "\t\t\trun = List.get(code, $pc + 1) ?? 0\n" ++
                    "\t\t\tone = List.get(code, $pc + 2) ?? 0\n" ++
                    "\t\t\tmany = List.get(code, $pc + 3) ?? 0\n",
                .section => "\t\t\tbody = $pc + 1\n\t\t\tstop = body + w // 1048576\n",
                .inverted, .cond, .call => "",
                .text => unreachable,
            });
            const skips = op == .inverted or op == .cond;
            try writer.print("\t\t\t{s} = match (w // 16) % 65536 {{\n", .{
                if (skips) "skip" else "$parts",
            });
            try writer.writeAll(cases.written());
            try writer.print("\t\t\t\t_ => {s}\n\t\t\t}}\n", .{
                if (skips) "Bool.False" else "$parts",
            });
            try writer.writeAll(switch (op) {
                .str, .num, .len => "\t\t\t$pc = $pc + 2\n",
                .plural => "\t\t\t$pc = $pc + 4\n",
                .section => "\t\t\t$pc = stop\n",
                .inverted, .cond => "\t\t\t$pc = if skip $pc + 1 + w // 1048576 else $pc + 1\n",
                .call => "\t\t\t$pc = $pc + 1\n",
                .text => unreachable,
            });
        }
    }

    /// What an arm reads: `s1.title`, `s0`, and its type.
    const Arm = struct {
        selector: u16,
        value: []const u8,
        kind: contract_.Kind,
        type_: u16,
        signed: bool,
        self: bool,
    };

    /// One `selector => ...` arm of an op's match, when the op can read
    /// `read`.
    fn case(walker: *Walker, op: Op, read: Read, writer: *Writer) Error!void {
        const type_ = walker.module.contract.get(read.type_);
        const kind: contract_.Kind = if (type_.kind == .unknown) .str else type_.kind;
        var value_buffer: [256]u8 = undefined;
        const arm: Arm = .{
            .selector = read.selector,
            .value = if (read.name) |name|
                std.fmt.bufPrint(&value_buffer, "s{d}.{s}", .{ read.k, name }) catch unreachable
            else
                std.fmt.bufPrint(&value_buffer, "s{d}", .{read.k}) catch unreachable,
            .kind = kind,
            .type_ = read.type_,
            .signed = kind == .int and type_.name[0] == 'I',
            .self = read.name == null,
        };
        const written = switch (op) {
            .str, .num, .len, .plural => try arm_value(op, arm, writer),
            .inverted, .cond => try arm_skip(op, arm, writer),
            .section => try walker.arm_section(arm, read.k, writer),
            .call => try walker.arm_call(arm, writer),
            .text => unreachable,
        };
        if (written) walker.used[read.k] = true;
    }

    /// An arm appending a value's part.
    fn arm_value(op: Op, arm: Arm, writer: *Writer) Error!bool {
        const s = arm.selector;
        const number = if (arm.signed) "Signed" else "Unsigned";
        const to = if (arm.signed) "to_i64()" else "to_u64()";
        switch (op) {
            .str => {
                if (arm.kind != .str) return false;
                const line = "\t\t\t\t{d} => $parts.append(Value(run, {s}))\n";
                try writer.print(line, .{ s, arm.value });
            },
            .num => {
                if (arm.kind != .int) return false;
                try writer.print("\t\t\t\t{d} => $parts.append({s}(run, {s}.{s}))\n", .{
                    s,
                    number,
                    arm.value,
                    to,
                });
            },
            .len => {
                if (arm.kind != .list) return false;
                const line = "\t\t\t\t{d} => $parts.append(Unsigned(run, {s}.len()))\n";
                try writer.print(line, .{ s, arm.value });
            },
            .plural => {
                const n = switch (arm.kind) {
                    .list => "len()",
                    .int => to,
                    else => return false,
                };
                try writer.print(
                    "\t\t\t\t{d} => {{\n\t\t\t\t\tn = {s}.{s}\n" ++
                        "\t\t\t\t\t$parts.append({s}(run, n))" ++
                        ".append(Text(if n == 1 one else many))\n" ++
                        "\t\t\t\t}}\n",
                    .{ s, arm.value, n, if (arm.kind == .list) "Unsigned" else number },
                );
            },
            else => unreachable,
        }
        return true;
    }

    /// An arm saying whether to skip a body: `{{^x}}`, `{{?x}}`.
    fn arm_skip(op: Op, arm: Arm, writer: *Writer) Error!bool {
        const s = arm.selector;
        switch (arm.kind) {
            .bool => if (op == .inverted)
                try writer.print("\t\t\t\t{d} => {s}\n", .{ s, arm.value })
            else
                try writer.print("\t\t\t\t{d} => !({s})\n", .{ s, arm.value }),
            .list => {
                if (op != .inverted) return false;
                try writer.print("\t\t\t\t{d} => !({s}.is_empty())\n", .{ s, arm.value });
            },
            else => return false,
        }
        return true;
    }

    /// An arm running a body in the scope it opens: each of a list's
    /// elements, a record, a Bool when true. The child's walker takes the
    /// scopes from the one holding the field up.
    fn arm_section(walker: *Walker, arm: Arm, k: u8, writer: *Writer) Error!bool {
        if (arm.self) return false;
        const contract = walker.module.contract;
        const child = switch (arm.kind) {
            .list => contract.get(arm.type_).element,
            .record, .bool => arm.type_,
            else => return false,
        };
        if (!bytecode.is_scope(contract, walker.parents, child)) return false;
        var args: Writer.Allocating = .init(walker.gpa);
        for (k..walker.chain_len) |up| try args.writer.print("s{d}, ", .{up});
        const rest = args.written();
        const s = arm.selector;
        switch (arm.kind) {
            .list => try writer.print(
                "\t\t\t\t{d} => {{\n\t\t\t\t\tvar $p = $parts\n" ++
                    "\t\t\t\t\tfor e in {s} {{\n" ++
                    "\t\t\t\t\t\t$p = w{d}(e, {s}code, body, stop, $p)\n" ++
                    "\t\t\t\t\t}}\n\t\t\t\t\t$p\n\t\t\t\t}}\n",
                .{ s, arm.value, child, rest },
            ),
            .record => try writer.print(
                "\t\t\t\t{d} => w{d}({s}, {s}code, body, stop, $parts)\n",
                .{ s, child, arm.value, rest },
            ),
            .bool => try writer.print(
                "\t\t\t\t{d} => if {s} w{d}({s}, {s}code, body, stop, $parts)" ++
                    " else $parts\n",
                .{ s, arm.value, child, arm.value, rest },
            ),
            else => unreachable,
        }
        for (k..walker.chain_len) |up| walker.used[up] = true;
        return true;
    }

    /// An arm calling a partial over the field holding its context.
    fn arm_call(walker: *Walker, arm: Arm, writer: *Writer) Error!bool {
        const alias = walker.module.contract.get(arm.type_).alias;
        if (arm.self or arm.kind != .record or alias.len == 0) return false;
        const line = "\t\t\t\t{d} => {s}.walk(code, {s}, $parts)\n";
        try writer.print(line, .{ arm.selector, alias, arm.value });
        return true;
    }

    fn write_scope_type(walker: *Walker, t: u16, writer: *Writer) Writer.Error!void {
        const contract = walker.module.contract;
        if (t == contract.root) return writer.print("{s}.Ctx", .{walker.module.name});
        try contract_.write_line_as(contract, t, writer, .named);
    }
};

/// A type as `roc fmt` lays it out: on one line when it fits, else a
/// record one field per line, with a trailing comma.
fn write_type(
    contract: *const Contract,
    index: u16,
    indent: u8,
    writer: *Writer,
) Writer.Error!void {
    assert(indent < 64);
    var line_buffer: [line_columns_max]u8 = undefined;
    var line: Writer = .fixed(&line_buffer);
    const fits = if (contract_.write_line_as(contract, index, &line, .named)) |_|
        @as(usize, indent) * 4 + line.buffered().len <= line_columns_max
    else |_|
        false;
    if (fits) return writer.writeAll(line.buffered());
    const type_ = contract.get(index);
    if (index != contract.root and type_.alias.len > 0) {
        return writer.print("{s}.Ctx", .{type_.alias});
    }
    switch (type_.kind) {
        .list => {
            try writer.writeAll("List(\n");
            try write_tabs(indent + 1, writer);
            try write_type(contract, type_.element, indent + 1, writer);
            try writer.writeAll(",\n");
            try write_tabs(indent, writer);
            try writer.writeAll(")");
        },
        .record => {
            var buffer: [contract_.fields_max]contract_.Field = undefined;
            try writer.writeAll("{\n");
            for (contract.sorted_fields(index, &buffer)) |f| {
                try write_tabs(indent + 1, writer);
                try writer.print("{s} : ", .{f.name});
                try write_type(contract, f.type, indent + 1, writer);
                try writer.writeAll(",\n");
            }
            try write_tabs(indent, writer);
            try writer.writeAll("}");
        },
        .unknown, .str, .int, .bool, .other => unreachable,
    }
}

fn write_tabs(count: u8, writer: *Writer) Writer.Error!void {
    for (0..count) |_| try writer.writeAll("\t");
}
